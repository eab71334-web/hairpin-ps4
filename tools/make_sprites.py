#!/usr/bin/env python3
"""Turns art/sprites_src/<car>_0.png (white paint) + <car>_1.png (black paint), rendered from the Godot game by
tools/godot/sprites.gd, into native/src/sprites_data.cpp. Each car = shaded base RGB + alpha + paint mask (body area),
so the PS4 game can tint it with any of the phone game's paints at runtime."""
import os, sys
from PIL import Image
import numpy as np

SRC = os.path.join(os.path.dirname(__file__), '..', 'art', 'sprites_src')
OUT = os.path.join(os.path.dirname(__file__), '..', 'native', 'src', 'sprites_data.cpp')
ORDER = ["hatch", "buggy", "muscle", "sierra", "pickup", "charger", "coupe", "m4", "gt3", "hyper"]
SW = 176                                   # stored sprite width

def load(n, i):
    return Image.open(os.path.join(SRC, f'{n}_{i}.png')).convert('RGBA')

# union bbox of all renders -> common crop width, common bottom
bb = None
for n in ORDER:
    for i in (0, 1):
        b = load(n, i).split()[3].point(lambda v: 255 if v > 8 else 0).getbbox()
        bb = b if bb is None else (min(bb[0], b[0]), min(bb[1], b[1]), max(bb[2], b[2]), max(bb[3], b[3]))
x0, x1, y1 = bb[0] - 4, bb[2] + 4, bb[3] + 2
scale = SW / float(x1 - x0)
lines = ['// GENERATED by tools/make_sprites.py - do not edit.', '#include "sprites.h"', '#include <cstdint>', '']
table = []
for n in ORDER:
    a, b = load(n, 0), load(n, 1)
    top = min(a.split()[3].point(lambda v: 255 if v > 8 else 0).getbbox()[1], b.split()[3].point(lambda v: 255 if v > 8 else 0).getbbox()[1]) - 3
    crop = (x0, top, x1, y1)
    h = int(round((y1 - top) * scale))
    def prep(im):
        arr = np.asarray(im.crop(crop), dtype=np.float32) / 255.0
        arr[..., :3] *= arr[..., 3:4]                                   # premultiply before resizing
        pm = Image.fromarray((arr * 255).astype(np.uint8), 'RGBA').resize((SW, h), Image.LANCZOS)
        r = np.asarray(pm, dtype=np.float32) / 255.0
        al = r[..., 3:4]
        rgb = np.where(al > 0.004, r[..., :3] / np.maximum(al, 0.004), 0)
        return np.clip(rgb, 0, 1), al[..., 0]
    ra, aa = prep(a)
    rb, ab = prep(b)
    lum = lambda r: r @ np.array([0.299, 0.587, 0.114])
    mask = np.clip((lum(ra) - lum(rb)) / 0.55, 0, 1) * (aa > 0.2)
    mask = np.clip(mask * 1.15 - 0.05, 0, 1)
    data = np.zeros((h, SW, 5), np.uint8)
    data[..., :3] = (ra * 255 + 0.5).astype(np.uint8)
    data[..., 3] = (aa * 255 + 0.5).astype(np.uint8)
    data[..., 4] = (mask * 255 + 0.5).astype(np.uint8)
    flat = data.reshape(-1)
    lines.append(f'static const uint8_t D_{n}[{len(flat)}] = {{')
    for i in range(0, len(flat), 40):
        lines.append(','.join(str(int(v)) for v in flat[i:i + 40]) + ',')
    lines.append('};')
    table.append(f'    {{"{n}", {SW}, {h}, D_{n}}},')
    Image.fromarray(data[..., :4], 'RGBA').save(f'/tmp/spr_{n}_preview.png')
lines.append('const SpriteCar SPRITE_CARS[SPRITE_CAR_COUNT] = {')
lines += table
lines.append('};')
open(OUT, 'w').write('\n'.join(lines) + '\n')
print('wrote', OUT, os.path.getsize(OUT) // 1024, 'KB')
